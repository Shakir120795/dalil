export function dirFor(lang: string): "rtl" | "ltr" {
  return lang === "ur" || lang === "ar" ? "rtl" : "ltr";
}

export function resolveUiLang(override?: string | null): UiLang {
  let code = "";
  if (override && override !== "auto") code = override;
  if (!code) {
    try {
      const chat = localStorage.getItem("dalil_reply_lang");
      if (chat && chat !== "auto") code = chat;
    } catch { /* storage unavailable */ }
  }
  if (!code) {
    try { code = effectiveAnswerLang(getPrefs()); } catch { code = "en"; }
  }
  return validUiLang(code);
}

