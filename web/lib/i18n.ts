export type StrKey = keyof typeof en;

const PARTIALS: Partial<Record<UiLang, Partial<Record<StrKey, string>>>> = {};

type Dict = Record<StrKey, string>;
const cache = new Map<UiLang, Dict>();

export function getStrings(lang: UiLang): Dict {
  let d = cache.get(lang);
  if (!d) {
    d = { ...en, ...(PARTIALS[lang] ?? {}) } as Dict;
    cache.set(lang, d);
  }
  return d;
}

export function translate(lang: UiLang, key: StrKey, params?: Record<string, string | number>): string {
  let s = getStrings(lang)[key] ?? en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
  return s;
}

export type TFunc = (key: StrKey, params?: Record<string, string | number>) => string;

/**
 * The UI language for this page + a t() translator. Also syncs
 * <html lang/dir> so RTL (Urdu/Arabic) flips the layout. `override` is the
 * chat page's live reply-language choice (state), so picking a new language
 * in the selector re-localizes immediately.
 */
export function useUiLang(override?: string | null): { lang: UiLang; dir: "rtl" | "ltr"; t: TFunc } {
  const [lang, setLang] = useState<UiLang>("en");
  useEffect(() => {
    const l = resolveUiLang(override);
    setLang(l);
    try {
      document.documentElement.lang = l === "hinglish" ? "hi" : l;
      document.documentElement.dir = dirFor(l);
    } catch { /* non-browser */ }
  }, [override]);
  const t = useCallback<TFunc>((key, params) => translate(lang, key, params), [lang]);
  return { lang, dir: dirFor(lang), t };
}

