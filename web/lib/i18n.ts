// hinglish (Roman Hindi), ur, ar, bn, tr, id. Urdu and Arabic are RTL.
//
// Language resolution (same precedence as the chat's effReply):
//   explicit override (chat selector state) > dalil_reply_lang (last chat
//   choice) > prefs.answerLang, with 'auto' resolved via effectiveAnswerLang.
// A resolved language outside the 8 UI languages falls back to English UI
// (the AI answer still comes in that language — only the chrome is English).

